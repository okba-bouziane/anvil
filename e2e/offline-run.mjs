// Runs the packaged app with internet blocked, using the real model. See README.
import { _electron as electron } from '@playwright/test'
import { execFileSync } from 'node:child_process'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'

const [wrapper, shots] = process.argv.slice(2)
const data = fs.mkdtempSync(path.join(os.tmpdir(), 'anvil-off-'))
const root = fs.realpathSync(fs.mkdtempSync(path.join(os.tmpdir(), 'invoice-api-')))
fs.mkdirSync(path.join(root, 'src'))
fs.mkdirSync(path.join(root, 'node_modules'))
fs.symlinkSync(path.resolve('node_modules/typescript'), path.join(root, 'node_modules/typescript'))
fs.writeFileSync(path.join(root, 'package.json'), '{"name":"invoice-api","type":"module"}\n')
fs.writeFileSync(path.join(root, 'tsconfig.json'), JSON.stringify({ compilerOptions: { strict: true, target: 'ES2022', module: 'NodeNext', moduleResolution: 'NodeNext', noEmit: true, skipLibCheck: true, types: [] }, include: ['src'] }, null, 2))
fs.writeFileSync(path.join(root, 'src/money.ts'), 'export function roundCents(value: number): number {\n  return Math.round(value * 100) / 100\n}\n')
fs.writeFileSync(path.join(root, 'src/invoice.ts'), "import { roundCents } from './money.js'\n\nexport interface Line {\n  price: number\n  quantity: number\n}\n\nexport function subtotal(lines: Line[]): number {\n  return roundCents(lines.reduce((sum, line) => sum + line.price * line.quantity, 0))\n}\n")
fs.writeFileSync(path.join(data, 'settings.json'), JSON.stringify({ lastProject: root }))
const app = await electron.launch({ executablePath: wrapper, env: { ...process.env, ANVIL_DATA_DIR: data } })
const page = await app.firstWindow()
await page.waitForSelector('.tree-row')
await page.screenshot({ path: `${shots}/1-ready.png` })
console.log('status before start:', (await page.locator('.model').innerText()).replace(/\n/g, ' '))

const started = Date.now()
await page.getByRole('button', { name: 'Start model' }).click()
await page.waitForSelector('.model.online', { timeout: 150000 })
console.log('model started by the app in', Math.round((Date.now() - started) / 1000), 's')

await page.locator('textarea').fill('Add a function total(lines: Line[], taxRate: number) to src/invoice.ts that adds tax to the subtotal and rounds to cents. Then add src/discount.ts with a function applyDiscount(amount: number, percent: number) that uses roundCents.')
await page.locator('textarea').press('Enter')
// This test checks the app, so any command the model asks for gets declined.
const decline = setInterval(() => void page.getByRole('button', { name: "Don't run" }).first().click({ timeout: 300 }).catch(() => {}), 1000)
await page.waitForSelector('.tool.running', { timeout: 120000 })
await page.waitForTimeout(1500)
await page.screenshot({ path: `${shots}/2-live.png` })
await page.waitForSelector('.checkpoint', { timeout: 300000 })
clearInterval(decline)
await page.locator('.change-row', { hasText: 'invoice.ts' }).click()
await page.waitForTimeout(1500)
await page.screenshot({ path: `${shots}/3-review.png` })
console.log('chat:', (await page.locator('.chat-list').innerText()).slice(-700))
console.log('changed files:', await page.locator('.change-row').allInnerTexts())
console.log('invoice.ts has total:', fs.readFileSync(path.join(root, 'src/invoice.ts'), 'utf8').includes('total'))
console.log('discount.ts exists:', fs.existsSync(path.join(root, 'src/discount.ts')))

console.log('code intelligence:', JSON.stringify(await page.evaluate(() => window.anvil.intel('hover', 'src/invoice.ts', 1, 11))))
await page.keyboard.press('Meta+j')
await page.waitForSelector('.xterm')
await page.waitForTimeout(1200)
await page.locator('.xterm').click()
await page.keyboard.type("curl -s -m 5 -o /dev/null -w 'internet-check %{http_code} ' https://huggingface.co; echo end-of-check\n")
await page.waitForFunction(() => document.querySelector('.xterm-rows')?.textContent?.includes('end-of-check'), null, { timeout: 15000 }).catch(() => {})
await page.waitForTimeout(6000)
console.log('terminal:', (await page.locator('.xterm-rows').innerText()).split('\n').filter((l) => l.includes('internet-check')).slice(-1)[0]?.trim())
await page.screenshot({ path: `${shots}/4-terminal.png` })
const pid = await app.evaluate(() => process.pid)
const tree = execFileSync('/bin/ps', ['-axo', 'pid,ppid,rss,command']).toString().split('\n').filter((l) => /Anvil/.test(l))
console.log('app memory MB:', Math.round(tree.reduce((n, l) => n + Number(l.trim().split(/\s+/)[2] || 0), 0) / 1024), 'processes', tree.length, 'main pid', pid)
await page.getByRole('button', { name: 'Settings' }).click()
await page.waitForTimeout(1200)
await page.screenshot({ path: `${shots}/5-models.png` })
console.log('models listed:', await page.locator('.model-row').allInnerTexts())
await page.getByRole('button', { name: 'Close', exact: true }).click()
await page.getByRole('button', { name: 'Stop model' }).click()
await page.waitForTimeout(2500)
console.log('after stop:', (await page.locator('.model').innerText()).replace(/\n/g, ' '))
await app.close()
